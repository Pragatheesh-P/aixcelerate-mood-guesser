last_digit = 3

N = last_digit if last_digit != 0 else 10

happy_master = [
    "won",
    "surprise",
    "excited",
    "selected",
    "tasty",
    "learned",
    "favourite",
    "marks",
    "party",
    "great"
]

sad_master = [
    "lost",
    "failed",
    "moving",
    "cancelled",
    "upset",
    "missed",
    "lonely",
    "stopped",
    "late",
    "rained"
]

happy_words = happy_master[:N]
sad_words = sad_master[:N]


def guess_mood(sentence):
    words = ""
    for ch in sentence:
        if ch.isalnum():
            words += ch.lower()
        else:
            words += " "

    words = words.split()

    happy_count = 0
    sad_count = 0

    for word in words:
        if word in happy_words:
            happy_count += 1

        if word in sad_words:
            sad_count += 1

    if happy_count > sad_count:
        return "Happy"
    else:

        return "Sad"
practice_data = [
    ("I won a medal in the sports meet", "Happy"),
    ("I lost my notebook before the exam", "Sad"),
    ("My friends gave me a lovely surprise", "Happy"),
    ("The train was late and I felt upset", "Sad"),
    ("Today was a great day", "Happy"),
]

correct = 0

for sentence, actual_mood in practice_data:
    predicted_mood = guess_mood(sentence)

    print("Sentence:", sentence)
    print("Predicted:", predicted_mood)
    print("Actual:", actual_mood)

    if predicted_mood == actual_mood:
        correct += 1

    print()

accuracy = (correct / len(practice_data)) * 100

print("Correct Answers:", correct)
print("Accuracy:", accuracy, "%")

